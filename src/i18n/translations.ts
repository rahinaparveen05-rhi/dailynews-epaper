export function localizeEditionMeta(
  meta: {
    dayOfWeek: string;
    formattedDate: string;
    cityEdition: string;
    volumeLabel?: string;
  },
  lang: LanguageCode,
): {
  dayOfWeek: string;
  formattedDate: string;
  cityEdition: string;
  volumeLabel: string;
} {
  if (lang === 'en') {
    return {
      dayOfWeek: meta.dayOfWeek,
      formattedDate: meta.formattedDate,
      cityEdition: meta.cityEdition,
      volumeLabel: meta.volumeLabel ?? '',
    };
  }
  const dayOfWeek = DAY_TRANSLATIONS[lang][meta.dayOfWeek] ?? meta.dayOfWeek;
  const cityEdition = CITY_EDITION_TRANSLATIONS[lang] ?? meta.cityEdition;
  let formattedDate = meta.formattedDate;
  for (const [enMonth, localMonth] of Object.entries(DATE_MONTH_TRANSLATIONS[lang])) {
    if (new RegExp(`^${enMonth}\\b`).test(formattedDate)) {
      formattedDate = formattedDate.replace(enMonth, localMonth);
      break;
    }
  }
  const volLabels = VOLUME_LABELS[lang];
  const volumeLabel = (meta.volumeLabel ?? '')
    .replace(/\bVol\./g, volLabels.vol)
    .replace(/\bNo\./g, volLabels.no);
  return { dayOfWeek, formattedDate, cityEdition, volumeLabel };
}

export function localizeArticle(
  article: NewspaperArticle,
  lang: LanguageCode,
): NewspaperArticle {
  if (lang === 'en') return article;
  const override = ARTICLE_TRANSLATIONS[lang]?.[article.id];
  const localizedEditionDate = localizeEditionMeta(
    { dayOfWeek: '', formattedDate: article.editionDate, cityEdition: '' },
    lang,
  ).formattedDate;

  if (!override) {
    return {
      ...article,
      editionDate: localizedEditionDate,
    };
  }

  return {
    ...article,
    editionDate: localizedEditionDate,
    headline: override.headline ?? article.headline,
    deck: override.deck ?? article.deck,
    byline: override.byline ?? article.byline,
    location: override.location ?? article.location,
    imageCaption: override.imageCaption ?? article.imageCaption,
    paragraphs: override.paragraphs ?? article.paragraphs,
  };
}

